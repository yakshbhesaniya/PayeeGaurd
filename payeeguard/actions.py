"""Finished work (spec section 11): what PayeeGuard hands over for each decision. Everything is a draft or
simulation and says so; no email is sent and no money moves."""

from .models import Action, Verdict

BANNER = "> SIMULATED / DRAFT: generated by PayeeGuard, not sent, no money moved.\n\n"


def _fmt_amount(inv) -> str:
    return f"{inv.currency or ''} {inv.amount:,.2f}".strip() if inv.amount is not None else "amount not stated"


def _contact(cb: dict | None) -> str:
    if not cb:
        return "the vendor's official website (look it up independently, never from the email)"
    parts = [p for p in (cb.get("phone"), cb.get("email")) if p]
    where = cb.get("website") or ""
    return (" / ".join(parts) + (f" (official site {where})" if where else "")) if parts else f"the official site {where}"


def _top(verdict: Verdict, n=4) -> str:
    rows = sorted((e for e in verdict.evidence if e.status == "contradicted"),
                  key=lambda e: (not e.hard_block, -e.weight))[:n]
    return "\n".join(f"- {e.detail} — `{e.source}`" for e in rows) or "- No contradictions; verification incomplete."


def build(verdict: Verdict, inv, ctx) -> list[Action]:
    cb = ctx.get("callback")
    vendor = ctx.get("vendor_label") or inv.vendor_name or "the vendor"
    fp = ctx.get("fp")
    acct = fp.masked if fp else "account on file"
    hyp = verdict.hypothesis
    out: list[Action] = []
    if verdict.decision == "PAY":
        out.append(Action("payment_instruction", "Payment instruction (queued at the gate)",
                          BANNER + f"Pay {_fmt_amount(inv)} to {vendor} ({acct}) for invoice {inv.invoice_number or '?'}.\n"
                          f"Risk {verdict.risk_score}, confidence {verdict.confidence}, rule {verdict.decision_rule}.\n"
                          f"Release with `pay_invoice('{verdict.case_id}')`."))
    elif verdict.decision == "HOLD":
        questions = ctx.get("challenge_questions") or []
        qs = "".join(f"{i}. {q}\n" for i, q in enumerate(questions, 3))
        out.append(Action("callback_script", "Callback script",
                          BANNER + f"Call {vendor} on {_contact(cb)}. This contact was found independently, not taken "
                          f"from the email.\n\nAsk:\n1. Did you send invoice {inv.invoice_number or '(number)'} for "
                          f"{_fmt_amount(inv)}?\n2. Please confirm the last 4 digits of the account you want paid "
                          f"(the email says {acct}).\n{qs}\nPay only if both answers match. Then run "
                          f"`resolve_case('{verdict.case_id}', 'approve', ...)`."))
        to = (cb or {}).get("email") or "the vendor's official contact"
        out.append(Action("verification_email_draft", "Verification email draft",
                          BANNER + f"To: {to}\nSubject: Please confirm payment details for invoice "
                          f"{inv.invoice_number or ''}\n\nHello {vendor} team,\n\nWe received a request to pay "
                          f"{_fmt_amount(inv)} to {acct}. Before paying, please confirm this request through your usual "
                          "contact with us. Do not reply to the original email thread.\n\nThank you,\nAccounts Payable"))
        out.append(Action("exception_ticket", "Exception ticket for a human",
                          BANNER + f"Case {verdict.case_id}: {verdict.summary}\n\nDecision needed: approve or reject "
                          f"payment of {_fmt_amount(inv)} to {acct}.\nWhy it was held ({verdict.decision_rule}):\n"
                          + _top(verdict)))
        if any(e.check == "C1_vendor" and e.status == "unchecked" and e.unchecked_reason == "no_data"
               for e in verdict.evidence):
            out.append(Action("kyb_onboarding_task", "Vendor onboarding (KYB) task",
                              BANNER + f"{vendor} is not in Crustdata and has no payment history. Collect: "
                              "registration certificate, GST/tax ID, bank letter on letterhead, a contact verified by "
                              "phone. Then run `onboard_vendor` and re-verify."))
    else:
        out.append(Action("fraud_case_file", "Fraud case file (complaint-ready)", case_file(verdict, inv, ctx)))
        out.append(Action("do_not_pay_notice", "Do-not-pay notice for the AP team",
                          BANNER + f"DO NOT PAY {_fmt_amount(inv)} to {acct} (case {verdict.case_id}).\n"
                          f"Reason: {hyp.title if hyp else verdict.decision_rule}."))
        if cb:
            out.append(Action("verification_email_draft", "Warning to the real vendor (draft)",
                              BANNER + f"To: {cb.get('email') or 'official contact'}\nSubject: Someone is impersonating "
                              f"{vendor}\n\nWe received a payment request in your name that we believe is fraudulent "
                              f"(account {acct}). Please check whether your mailbox or domain has been compromised."))
    return out


def case_file(verdict: Verdict, inv, ctx) -> str:
    hyp = verdict.hypothesis
    related = ctx.get("related_cases") or []
    lines = [BANNER + f"# Fraud case file {verdict.case_id}", "",
             "## 1. Summary",
             f"Decision **BLOCK** (risk {verdict.risk_score}, rule {verdict.decision_rule}). Amount at risk: "
             f"{_fmt_amount(inv)}.",
             f"Most likely: **{hyp.title}** (`{hyp.attack_type}`). {hyp.narrative}" if hyp else "",
             "Ruled out: " + ("; ".join(f"{r.attack_type} ({r.because})" for r in verdict.ruled_out) or "none"), "",
             "## 2. Timeline",
             f"- Received: {ctx.get('received_at')}",
             f"- Claimed vendor: {inv.vendor_name or '?'}; claimed sender: {inv.sender_name or '-'} <{inv.sender_email or '?'}>",
             f"- Request: pay invoice {inv.invoice_number or '?'}"
             + (" with **changed bank details**" if inv.bank_change_requested else ""), "",
             "## 3. Indicators of compromise",
             f"- Sender address: {inv.sender_email or '-'}",
             f"- Reply-To: {inv.reply_to_email or '-'}",
             f"- Payment account: {ctx['fp'].masked if ctx.get('fp') else '-'} (SWIFT/IFSC {inv.bank_swift or '-'})", "",
             "## 4. Identity findings (Crustdata)",
             f"- Real vendor: {ctx.get('vendor_label') or 'not resolved'}",
             f"- Vendor domains: {', '.join(sorted(ctx.get('real_domains') or [])) or 'unknown'}", "",
             "## 5. Graph findings"]
    lines += [f"- Linked blocked case {c}" for c in related] or ["- No earlier linked cases"]
    lines += ["", "## 6. Evidence ledger", "| Check | Result | Detail | Source |", "|---|---|---|---|"]
    lines += [f"| {e.check} | {e.status.upper() if e.status == 'contradicted' else e.status} | {e.detail} | `{e.source}` |"
              for e in verdict.evidence]
    lines += ["", "## 7. Recommended actions",
              "1. Do not pay. 2. Warn the real vendor through its official channel (draft attached).",
              "3. Report: India cybercrime.gov.in / helpline 1930; US ic3.gov. 4. Preserve the original email with headers.",
              "", "## 8. Chain of custody",
              f"case_id {verdict.case_id} · generated {ctx.get('received_at')} · PayeeGuard {ctx.get('version')}"]
    return "\n".join(lines)
